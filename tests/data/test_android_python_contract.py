    ingested = AndroidExportReader.ingest_csv_export(csv_path)
    assert ingested.audit["raw_records"] == 22
    assert ingested.audit["accepted_records"] == 20
    assert ingested.audit["rejected_records"] == 2
    assert ingested.audit["rejected_by_reason"] == {
        "NON_FINITE_VALUE": 1,
        "OUT_OF_RANGE_EXCESSIVE_G": 1,
    }
    # No fabricated zero-valued accelerometer observations in accepted rows
    cleaned, clean_audit = DataCleaner.clean_accelerometer_with_audit(ingested.accepted)
    validated = RawAccelerometerSchema.validate(cleaned)
    assert len(validated) == 20
    assert clean_audit["dropped_non_finite_or_null"] == 0
    assert all(x != 0.0 for x in validated["x"].to_list())


