def _sample_features_df(sessions: list[str]) -> pl.DataFrame:
    rows = []
    idx = 0
    for sid in sessions:
        for k in range(2):
            rows.append({
                "window_id": f"{sid}-w{k:05d}",
                "session_id": sid,
                "start_utc_millis": 1_700_000_000_000 + idx * 1_000,
                "end_utc_millis": 1_700_000_000_950 + idx * 1_000,
                "sample_count": 20,
                "coverage_fraction": 1.0,
                "motion_rms": 0.02,
                "variance": 0.001,
                "jerk": 0.01,
                "mean_hr": 62.0,
                "hr_available": True,
                "label": "REST",
                "provenance": "PHONE_REAL",
            })
            idx += 1
    return pl.DataFrame(rows)


def test_de008_parquet_rebuild_removes_stale_partitions_and_preserves_on_failure(tmp_path: Path) -> None:
    out_dir = tmp_path / "parquet_ds"
    unrelated_sibling = tmp_path / "unrelated_note.txt"
    unrelated_sibling.write_text("do not touch", encoding="utf-8")

    # 1. First build: sessions A and B
    df_ab = _sample_features_df(["session-A", "session-B"])
    DatasetBuilder.build_parquet_dataset(df_ab, out_dir)
    loaded_ab = DatasetBuilder.load_parquet_dataset(out_dir)
    assert set(loaded_ab["session_id"].unique().to_list()) == {"session-A", "session-B"}

    # 2. Rebuilding without replace_output=True is rejected
    df_a = _sample_features_df(["session-A"])
    with pytest.raises(FileExistsError):
        DatasetBuilder.build_parquet_dataset(df_a, out_dir, replace_output=False)

    # 3. Second authorized build: only session A -> session B partition is gone!
    DatasetBuilder.build_parquet_dataset(df_a, out_dir, replace_output=True)
    loaded_a = DatasetBuilder.load_parquet_dataset(out_dir)
    assert set(loaded_a["session_id"].unique().to_list()) == {"session-A"}
    meta_a = json.loads((out_dir / "dataset_metadata.json").read_text(encoding="utf-8"))
    assert meta_a["sessions"] == ["session-A"]

    # 4. Injected failure before publication preserves previous dataset and sibling files
    def _boom(_staging: Path) -> None:
        raise RuntimeError("simulated pre-publish failure")

    with pytest.raises(RuntimeError, match="simulated pre-publish failure"):
        DatasetBuilder.build_parquet_dataset(df_ab, out_dir, replace_output=True, _pre_publish_hook=_boom)

    loaded_after_fail = DatasetBuilder.load_parquet_dataset(out_dir)
    assert set(loaded_after_fail["session_id"].unique().to_list()) == {"session-A"}
    assert unrelated_sibling.read_text(encoding="utf-8") == "do not touch"
    assert [p.name for p in tmp_path.iterdir() if ".staging-" in p.name] == []

    # 5. Deterministic content_sha256 and metadata across rebuilds
    out_dir_2 = tmp_path / "parquet_ds_copy"
    DatasetBuilder.build_parquet_dataset(df_a, out_dir_2)
    meta_copy = json.loads((out_dir_2 / "dataset_metadata.json").read_text(encoding="utf-8"))
    assert meta_a == meta_copy


