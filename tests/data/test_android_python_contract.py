    lines = [
        "# SleepSense Ground-Truth Accelerometry Dataset v2.0",
        "# SessionId: de004-session",
        "# ExperimentType: CONTROLLED_REST",
        "# Placement: MATTRESS",
        "# GroundTruthActivity: RESTING",
        "timestamp_utc_ms,elapsed_realtime_ns,accel_x,accel_y,accel_z,dynamic_magnitude,is_valid,ground_truth_label,predicted_motion_class,rejection_reason,source_kind",
    ]
