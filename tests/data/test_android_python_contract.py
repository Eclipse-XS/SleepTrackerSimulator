def test_de006_ten_samples_five_second_gap_ten_samples_never_spans_gap() -> None:
    # 10 samples at 20 Hz (0..450ms), then a 5-second gap, then 10 samples at 20 Hz (5450..5900ms)
    times_ms = [i * 50 for i in range(10)] + [5_450 + i * 50 for i in range(10)]
    accel = pl.DataFrame({
        "session_id": ["gap-sess"] * 20,
        "source_id": ["accel"] * 20,
        "elapsed_nanos": [(1_000 + t) * 1_000_000 for t in times_ms],
        "utc_millis": [1_700_000_000_000 + t for t in times_ms],
        "x": [0.01] * 20,
        "y": [-0.01] * 20,
        "z": [9.80665] * 20,
        "accuracy": [3] * 20,
        "source_kind": ["PHONE_REAL"] * 20,
    })

    diag = SensorSynchronizer.synchronize_with_diagnostics(accel, _make_hr([]))
    # 1. No fabricated valid 20-sample continuous window spanning the gap
    assert diag.accepted_windows == []
    # 2. The 5-second gap appears in quality diagnostics
    assert diag.inter_fragment_gaps_ms == [5_000]
    assert diag.to_dict()["max_inter_fragment_gap_ms"] == 5_000
    # 3. Neither fragment receives 100% coverage even though the input had 20 rows total
    assert len(diag.rejected_windows) == 2
    for rw in diag.rejected_windows:
        assert rw["raw_sample_count"] == 10
        assert rw["coverage_fraction"] == pytest.approx(0.50)
        assert rw["has_large_gap"] is True
        assert rw["training_eligible"] is False


