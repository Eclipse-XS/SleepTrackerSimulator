    lines.append("1700000001000,2000000000,NaN,0.00000,9.80500,NaN,false,RESTING,ACTIVE,NON_FINITE_VALUE,PHONE_REAL")
    lines.append("1700000001050,2050000000,250.00000,0.00000,9.80500,240.38800,false,RESTING,ACTIVE,OUT_OF_RANGE_EXCESSIVE_G,PHONE_REAL")

    csv_path = tmp_path / "de004.csv"
