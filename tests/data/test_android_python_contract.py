def _make_20_sample_accel(session_id: str = "s1", start_utc: int = 100_000) -> pl.DataFrame:
    # 20 samples at t = start_utc + 0, 50, ..., 950 -> prediction_cutoff = start_utc + 950
    return pl.DataFrame({
        "session_id": [session_id] * 20,
        "source_id": ["accel"] * 20,
        "elapsed_nanos": [(1_000 + i * 50) * 1_000_000 for i in range(20)],
        "utc_millis": [start_utc + i * 50 for i in range(20)],
        "x": [0.0] * 20,
        "y": [0.0] * 20,
        "z": [9.80665] * 20,
        "accuracy": [3] * 20,
        "source_kind": ["PHONE_REAL"] * 20,
    })


def _make_hr(rows: list[tuple[str, int, int, str]]) -> pl.DataFrame:
    if not rows:
        return pl.DataFrame(schema={"session_id": pl.String, "device_id": pl.String, "bpm": pl.Int32, "utc_millis": pl.Int64, "source_kind": pl.String})
    return pl.DataFrame({
        "session_id": [r[0] for r in rows],
        "device_id": ["band"] * len(rows),
        "bpm": [r[1] for r in rows],
        "utc_millis": [r[2] for r in rows],
        "source_kind": [r[3] for r in rows],
    })


def test_de005_all_mandatory_hr_cutoff_edge_cases() -> None:
    accel = _make_20_sample_accel("s1", start_utc=100_000)
    cutoff = 100_950  # last accel sample in the window (nominal window end is 101_000)

    # 1. HR exactly at prediction cutoff -> accepted (latest eligible sample selected, not average)
    w_exact = SensorSynchronizer.create_synchronized_windows(
        accel, _make_hr([("s1", 60, cutoff - 2_000, "BLE_REAL"), ("s1", 72, cutoff, "BLE_REAL")])
    )[0]
    assert w_exact["prediction_cutoff_utc"] == cutoff
    assert w_exact["hr_available"] is True
    assert w_exact["mean_hr"] == 72.0  # latest sample, NOT (60+72)/2 = 66.0

    # 2. HR 1 ms after prediction cutoff -> rejected
    w_plus_1 = SensorSynchronizer.create_synchronized_windows(
        accel, _make_hr([("s1", 72, cutoff + 1, "BLE_REAL")])
    )[0]
    assert w_plus_1["hr_available"] is False
    assert w_plus_1["mean_hr"] is None

    # 3. HR 10,000 ms before cutoff -> accepted
    w_10s = SensorSynchronizer.create_synchronized_windows(
        accel, _make_hr([("s1", 64, cutoff - 10_000, "BLE_REAL")])
    )[0]
    assert w_10s["hr_available"] is True
    assert w_10s["mean_hr"] == 64.0

    # 4. HR 10,001 ms before cutoff -> rejected as stale
    w_stale = SensorSynchronizer.create_synchronized_windows(
        accel, _make_hr([("s1", 64, cutoff - 10_001, "BLE_REAL")])
    )[0]
    assert w_stale["hr_available"] is False
    assert w_stale["mean_hr"] is None
    assert "STALE_HEART_RATE" in w_stale["quality_flags"]

    # 5. HR from a different session -> rejected
    w_other_sess = SensorSynchronizer.create_synchronized_windows(
        accel, _make_hr([("other-session", 68, cutoff, "BLE_REAL")])
    )[0]
    assert w_other_sess["hr_available"] is False
    assert w_other_sess["mean_hr"] is None

    # 6. No eligible HR -> hr_available=False, no artificial BPM
    w_none = SensorSynchronizer.create_synchronized_windows(accel, _make_hr([]))[0]
    assert w_none["hr_available"] is False
    assert w_none["mean_hr"] is None

    # 7. HR between last accel sample (100_950) and nominal 1s boundary (101_000) -> rejected!
    w_between = SensorSynchronizer.create_synchronized_windows(
        accel, _make_hr([("s1", 95, 100_980, "WEBSOCKET_SIMULATED")])
    )[0]
    assert w_between["window_end_utc"] == 101_000
    assert w_between["prediction_cutoff_utc"] == 100_950
    assert w_between["hr_available"] is False
    assert w_between["mean_hr"] is None


