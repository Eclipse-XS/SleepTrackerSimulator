def test_de002_annotations_transitions_and_predictions_remain_separate() -> None:
    csv_ingested = AndroidExportReader.ingest_csv_export(CSV_FIXTURE)
    json_ingested = AndroidExportReader.ingest_json_export(JSON_FIXTURE)

    # Same session metadata from CSV and JSON
    for key in ("session_id", "experiment_type", "placement", "ground_truth_activity", "device_model", "schema_version"):
        assert csv_ingested.metadata[key] == json_ingested.metadata[key], key
    assert csv_ingested.metadata["session_id"] == "fixture-contract-session-001"
    assert csv_ingested.metadata["experiment_type"] == "READING_IN_BED"
    assert csv_ingested.metadata["placement"] == "NIGHTSTAND"

    # 80 raw rows -> 78 accepted + 2 rejected (NON_FINITE_VALUE, OUT_OF_RANGE_EXCESSIVE_G)
    assert csv_ingested.audit["raw_records"] == 80
    assert csv_ingested.audit["accepted_records"] == 78
    assert csv_ingested.audit["rejected_records"] == 2
    assert csv_ingested.audit["rejected_by_reason"] == {
        "NON_FINITE_VALUE": 1,
        "OUT_OF_RANGE_EXCESSIVE_G": 1,
    }
    assert json_ingested.audit["raw_records"] == 80
    assert json_ingested.audit["accepted_records"] == 78
    assert json_ingested.audit["rejected_records"] == 2
    assert json_ingested.audit["rejected_by_reason"] == csv_ingested.audit["rejected_by_reason"]

    # RESTING -> READING transition survives unchanged in both formats
    activities_csv = csv_ingested.accepted["ground_truth_activity"].to_list()
    activities_json = json_ingested.accepted["ground_truth_activity"].to_list()
    assert activities_csv == activities_json
    assert activities_csv[:29] == ["RESTING"] * 29  # 30 raw minus 1 rejected NaN at index 10
    assert activities_csv[29:] == ["READING"] * 49  # 50 raw minus 1 rejected 500g at index 45

    # predicted_motion_class=ACTIVE never becomes a supervised ACTIVE training label
    assert "ACTIVE" in csv_ingested.accepted["predicted_motion_class"].to_list()
    assert set(csv_ingested.accepted["motion_class_label"].to_list()) == {"UNLABELED"}


