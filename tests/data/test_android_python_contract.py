def test_ml002_group_split_disjointness_determinism_and_error_handling() -> None:
    sessions = [f"sess-{i:02d}" for i in range(10) for _ in range(5)]
    s42_a = split_by_group(sessions, val_ratio=0.20, test_ratio=0.20, seed=42)
    s42_b = split_by_group(sessions, val_ratio=0.20, test_ratio=0.20, seed=42)
    s99 = split_by_group(sessions, val_ratio=0.20, test_ratio=0.20, seed=99)

    # Disjointness
    assert s42_a.train_sessions.isdisjoint(s42_a.val_sessions)
    assert s42_a.train_sessions.isdisjoint(s42_a.test_sessions)
    assert s42_a.val_sessions.isdisjoint(s42_a.test_sessions)
    assert len(s42_a.train_sessions | s42_a.val_sessions | s42_a.test_sessions) == 10

    # Fixed seed -> identical; different seed -> different allocation
    assert s42_a.train_sessions == s42_b.train_sessions
    assert s42_a.val_sessions == s42_b.val_sessions
    assert s42_a.test_sessions == s42_b.test_sessions
    assert (s42_a.train_sessions, s42_a.val_sessions, s42_a.test_sessions) != (
        s99.train_sessions,
        s99.val_sessions,
        s99.test_sessions,
    )

    # Subject-aware split keeps multiple sessions of one subject together
    subj_sessions = ["s1", "s2", "s3", "s4", "s5", "s6"]
    subj_ids = ["subj-A", "subj-A", "subj-B", "subj-B", "subj-C", "subj-C"]
    subj_split = split_by_group(subj_sessions, subject_ids=subj_ids, val_ratio=0.33, test_ratio=0.33, seed=7)
    assert subj_split.group_kind == "subject_id"
    for pair in ({"s1", "s2"}, {"s3", "s4"}, {"s5", "s6"}):
        assert (
            pair.issubset(subj_split.train_sessions)
            or pair.issubset(subj_split.val_sessions)
            or pair.issubset(subj_split.test_sessions)
        )

    # Fewer than 3 groups -> explicit ValueError
    with pytest.raises(ValueError, match="At least 3 distinct"):
        split_by_group(["only-1", "only-1", "only-2", "only-2"])


