"""End-to-End integration test: Android Export -> Ingestion -> Polars -> Parquet -> DuckDB.

Verifies that exports generated by Android's DatasetCsvExporter.generateCsv
are completely compatible with Python's data engineering pipeline, and that
schema incompatibilities are deterministically caught.
"""

from __future__ import annotations

import tempfile
from pathlib import Path

import polars as pl
import pytest

from pipelines.analytics.duckdb_analytics import SleepDataAnalytics
from pipelines.datasets.dataset_builder import DatasetBuilder
from pipelines.features.feature_extractor import FeatureExtractor
from pipelines.ingestion.android_export_reader import AndroidExportReader
from pipelines.transformation.cleaning import DataCleaner
from pipelines.transformation.synchronizer import SensorSynchronizer


def generate_mock_android_csv(session_id: str = "android-test-session-001", num_samples: int = 60) -> str:
    """Generates exact CSV string matching Android DatasetCsvExporter.generateCsv format."""
    lines = [
        "# SleepSense Ground-Truth Accelerometry Dataset v2.0",
        f"# SessionId: {session_id}",
        "# ExperimentType: CONTROLLED_REST",
        "# Placement: MATTRESS",
        "# GroundTruthActivity: RESTING",
        "# DeviceModel: Google Pixel 8 Pro",
        "# StartTimeUtc: 2026-10-29T10:00:00.000Z",
        "# EndTimeUtc: 2026-10-29T10:00:03.000Z",
        "# DurationSeconds: 3.000",
        f"# TotalSamples: {num_samples}",
        f"# ValidSamples: {num_samples}",
        "# RejectedSamples: 0",
        "# ActualSamplingRateHz: 20.00",
        "timestamp_utc_ms,elapsed_realtime_ns,accel_x,accel_y,accel_z,dynamic_magnitude,is_valid,ground_truth_label,predicted_motion_class",
    ]

    for i in range(num_samples):
        utc = 1700000000000 + i * 50
        elapsed = 1000000000 + i * 50_000_000
        x = 0.012 + (0.001 * (i % 3))
        y = -0.015 + (0.001 * (i % 2))
        z = 9.805 + (0.002 * (i % 4))
        dyn = 0.015
        lines.append(f"{utc},{elapsed},{x:.5f},{y:.5f},{z:.5f},{dyn:.5f},true,RESTING,REST")

    return "\n".join(lines)


def test_android_csv_export_to_duckdb_e2e_pipeline() -> None:
    """Full lifecycle: Android CSV export from actual Android code -> DuckDB analytics."""
    real_csv_source = Path("build/real_exports/android_actual_export.csv")
    with tempfile.TemporaryDirectory() as tmp_dir:
        tmp_path = Path(tmp_dir)
        csv_file = tmp_path / "actual_android_export.csv"

        if real_csv_source.exists():
            csv_file.write_text(real_csv_source.read_text(encoding="utf-8"), encoding="utf-8")
        else:
            # Fallback if running outside full Gradle build
            target_session_id = "session-e2e-real-export-42"
            csv_content = generate_mock_android_csv(session_id=target_session_id, num_samples=80)
            csv_file.write_text(csv_content, encoding="utf-8")

        # 1. Ingestion: AndroidExportReader
        accel_df = AndroidExportReader.read_csv_export(csv_file)
        assert len(accel_df) == 80
        target_session_id = accel_df["session_id"][0]
        assert "x" in accel_df.columns
        assert "y" in accel_df.columns
        assert "z" in accel_df.columns
        assert "utc_millis" in accel_df.columns
        assert "elapsed_nanos" in accel_df.columns

        # 2. Data Cleaning
        cleaned_accel = DataCleaner.clean_accelerometer(accel_df)
        assert len(cleaned_accel) == 80

        # 3. Synchronization (accelerometer-only session, no HR available)
        empty_hr = pl.DataFrame({
            "session_id": pl.Series([], dtype=pl.Utf8),
            "device_id": pl.Series([], dtype=pl.Utf8),
            "bpm": pl.Series([], dtype=pl.Int32),
            "utc_millis": pl.Series([], dtype=pl.Int64),
            "source_kind": pl.Series([], dtype=pl.Utf8),
        })
        windows = SensorSynchronizer.create_synchronized_windows(cleaned_accel, empty_hr, window_size=20)
        assert len(windows) == 4  # 80 samples / 20 = 4 windows

        # 4. Feature Extraction (default path: unmapped activity -> label is UNLABELED, ground_truth_activity preserved)
        feature_rows = [FeatureExtractor.extract_window_features(w) for w in windows]
        assert len(feature_rows) == 4
        assert all(row["ground_truth_activity"] == "RESTING" for row in feature_rows)
        assert all(row["label"] == "UNLABELED" for row in feature_rows)
        assert all(row["training_eligible"] is False for row in feature_rows)
        assert all(row["hr_available"] is False for row in feature_rows)

        features_df = pl.DataFrame(feature_rows)

        # 5. Parquet Dataset Build
        dataset_dir = tmp_path / "parquet_dataset"
        DatasetBuilder.build_parquet_dataset(features_df, dataset_dir)
        assert (dataset_dir / "dataset_metadata.json").exists()

        # 6. DuckDB SQL Analytics Query
        analytics = SleepDataAnalytics(dataset_dir)
        summaries = analytics.get_session_summaries()
        assert len(summaries) == 1
        assert summaries["session_id"][0] == target_session_id
        assert summaries["total_windows"][0] == 4
        assert summaries["hr_coverage_pct"][0] == 0.0

        class_dist = analytics.get_class_distributions()
        assert len(class_dist) == 1
        assert class_dist["label"][0] == "UNLABELED"
        assert class_dist["window_count"][0] == 4


def test_schema_incompatibility_raises_deterministic_error() -> None:
    """Verifies that future schema breakages in Android export column names are caught immediately."""
    with tempfile.TemporaryDirectory() as tmp_dir:
        bad_csv = Path(tmp_dir) / "corrupted_schema.csv"
        # Incompatible headers missing timestamp and coordinates
        bad_csv.write_text(
            "# SessionId: broken-001\n"
            "unknown_col_1,unknown_col_2,unknown_col_3\n"
            "123,456,789\n",
            encoding="utf-8"
        )

        with pytest.raises((ValueError, KeyError, pl.exceptions.PolarsError)):
            # Must fail validation (ComputeError, SchemaError, or ColumnNotFoundError)
            AndroidExportReader.read_csv_export(bad_csv)


def test_json_export_reader_compatibility() -> None:
    """Verifies that Android JSON export parsing works identically on actual Android exports."""
    real_json_source = Path("build/real_exports/android_actual_export.json")
    with tempfile.TemporaryDirectory() as tmp_dir:
        json_file = Path(tmp_dir) / "session_export.json"
        if real_json_source.exists():
            json_file.write_text(real_json_source.read_text(encoding="utf-8"), encoding="utf-8")
            accel_df, hr_df = AndroidExportReader.read_json_export(json_file)
            assert len(accel_df) == 80
            assert len(hr_df) == 4
            assert hr_df["bpm"][0] == 65
        else:
            json_file.write_text(
                """{
                    "sessionId": "json-session-001",
                    "samples": [
                        {
                            "utcTimestampMillis": 1700000000000,
                            "elapsedRealtimeNanos": 1000000000,
                            "x": 0.012,
                            "y": -0.015,
                            "z": 9.805,
                            "sensorAccuracy": 3,
                            "sourceKind": "PHONE_REAL"
                        }
                    ],
                    "heartRateSamples": [
                        {
                            "deviceId": "band-42",
                            "bpm": 65,
                            "utcTimestampMillis": 1700000000000,
                            "sourceKind": "BLE_REAL"
                        }
                    ]
                }""",
                encoding="utf-8"
            )

            accel_df, hr_df = AndroidExportReader.read_json_export(json_file)
            assert len(accel_df) == 1
            assert accel_df["session_id"][0] == "json-session-001"
            assert accel_df["x"][0] == pytest.approx(0.012, abs=1e-3)
            assert len(hr_df) == 1
            assert hr_df["bpm"][0] == 65
